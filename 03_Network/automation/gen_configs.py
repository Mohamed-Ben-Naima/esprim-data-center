def cisco_mgmt_vrf(d):
    port = d["mgmt"]["port"]
    to = d["ports"][port]["to"]
    return [
        "! ---------------------------------------------------------------- OOB management (VRF, never routed in-band)",
        "vrf definition MGMT",
        " description Out-of-band management VLAN 10",
        " address-family ipv4",
        " exit-address-family",
        "!",
        f"interface {port}",
        f" description {label(d['_name'], port, to, 'OOB VLAN 10 (VRF MGMT)')}",
        *([" no switchport"] if d["platform"] == "iosvl2" else []),
        " vrf forwarding MGMT",
        f" ip address {d['mgmt']['ip']} {mask(VL[10]['subnet'])}",
        " no ip redirects",
        " no ip proxy-arp",
        " no shutdown",
        "!",
        f"ip route vrf MGMT 0.0.0.0 0.0.0.0 {VL[10]['vip']} name OOB-GW-FW",
        "!",
    ]


def unused_ports(d, all_ports, l2):
    L = []
    for p in all_ports:
        if p in d["ports"]:
            continue
        L += [f"interface {p}", " description UNUSED | parking (CIS: unused ports disabled)"]
        if l2:
            L += [" switchport mode access", " switchport access vlan 999", " switchport nonegotiate"]
        L += [" shutdown", "!"]
    return L


def gen_edge(name, d):
    d["_name"] = name
    L, mgmt_src, vrf = cisco_base(name, d)
    peer = "EDGE-B" if name == "EDGE-A" else "EDGE-A"
    ext = TR["ext"]
    L += cisco_mgmt_vrf(d)
    L += ["! ---------------------------------------------------------------- tracking (HSRP follows Internet reachability)",
          "track 10 ip route 0.0.0.0 0.0.0.0 reachability",
          " delay down 1 up 5",
          "!",
          "interface Loopback0",
          " description Router-ID / iBGP source",
          f" ip address {d['loopback']} 255.255.255.255",
          " ip ospf 1 area 0",
          "!"]
    # WAN anti-spoofing (RFC 1918 + own prefix + loopbacks)
    L += ["ip access-list extended ACL-WAN-IN",
          " remark anti-spoofing: private, own public prefix and bogon sources dropped",
          " deny   ip 10.0.0.0 0.255.255.255 any log",
          " deny   ip 172.16.0.0 0.15.255.255 any log",
          " deny   ip 192.168.0.0 0.0.255.255 any log",
          " deny   ip 127.0.0.0 0.255.255.255 any",
          f" deny   ip {net(SITE['public_prefix']).network_address} {wild(SITE['public_prefix'])} any log",
          " permit ip any any",
          "!"]
    for port, p in d["ports"].items():
        if p["mode"] == "mgmt":
            continue
        L += [f"interface {port}", f" description {label(name, port, p['to'], p['role'])}", f" ip address {ipmask(p['ip'])}"]
        if p["to"].startswith("ISP"):
            # no uRPF: the Edges only learn a default route from the ISPs and loose uRPF ignores it,
            # which would drop every Internet reply; anti-spoofing is enforced by ACL-WAN-IN
            L += [" ip access-group ACL-WAN-IN in",
                  " no ip redirects", " no ip unreachables", " no ip proxy-arp", " no cdp enable", " no lldp transmit"]
        elif p["to"].startswith("EDGE"):
            L += [" ip ospf network point-to-point", " ip ospf 1 area 0",
                  " ip ospf authentication message-digest", f" ip ospf message-digest-key 1 md5 {C['ospf_key']}",
                  " ip ospf hello-interval 1", " ip ospf dead-interval 3"]
        elif p["to"].startswith("SW-OUT"):
            L += [" no ip redirects", " no ip proxy-arp",
                  " ip ospf 1 area 0", " ip ospf authentication message-digest", f" ip ospf message-digest-key 1 md5 {C['ospf_key']}",
                  " standby version 2",
                  f" standby 1 ip {ext['edge_vip']}",
                  f" standby 1 priority {d['hsrp_ext_priority']}",
                  " standby 1 preempt delay minimum 30",
                  " standby 1 timers msec 250 msec 750",
                  f" standby 1 authentication md5 key-string {C['hsrp_key']}",
                  " standby 1 track 10 decrement 20",
                  " standby 1 name HSRP-TRANSIT-EXT"]
        L += [" no shutdown", "!"]
    L += unused_ports(d, [f"Gi0/{i}" for i in range(8)], l2=False)
    # routing
    isp_neigh = []
    for isp, i in INV["isps"].items():
        for port, link in i["links"].items():
            if link["peer"] == name:
                isp_neigh.append((isp, i, link))
    L += ["! ---------------------------------------------------------------- routing",
          "router ospf 1",
          f" router-id {d['loopback']}",
          " auto-cost reference-bandwidth 100000",
          " passive-interface default",
          " no passive-interface Gi0/2",
          " no passive-interface Gi0/3",
          " log-adjacency-changes detail",
          "!",
          f"ip prefix-list PL-ANNOUNCE seq 10 permit {SITE['public_prefix']}",
          "ip prefix-list PL-DEFAULT seq 10 permit 0.0.0.0/0",
          "!"]
    for isp, i, link in isp_neigh:
        L += [f"route-map RM-{isp}-IN permit 10",
              " description accept default only, set provider preference",
              " match ip address prefix-list PL-DEFAULT",
              f" set local-preference {i['lp_in']}",
              "!",
              f"route-map RM-{isp}-OUT permit 10",
              " description announce only our public prefix",
              " match ip address prefix-list PL-ANNOUNCE"]
        if i["prepend_out"]:
            L.append(" set as-path prepend " + " ".join([str(SITE["asn"])] * i["prepend_out"]))
        L += ["!"]
    peer_lo = DEV[peer]["loopback"]
    L += [f"router bgp {SITE['asn']}",
          f" bgp router-id {d['loopback']}",
          " bgp log-neighbor-changes",
          " no bgp default ipv4-unicast"]
    for isp, i, link in isp_neigh:
        L += [f" neighbor {link['ip']} remote-as {i['asn']}",
              f" neighbor {link['ip']} description {isp} (AS{i['asn']})",
              f" neighbor {link['ip']} password {C['bgp_password']}",
              f" neighbor {link['ip']} timers 3 9"]
    L += [f" neighbor {peer_lo} remote-as {SITE['asn']}",
          f" neighbor {peer_lo} description iBGP {peer}",
          f" neighbor {peer_lo} update-source Loopback0",
          f" neighbor {peer_lo} password {C['bgp_password']}",
          f" neighbor {peer_lo} timers 3 9",
          " !",
          " address-family ipv4",
          f"  network {net(SITE['public_prefix']).network_address} mask {mask(SITE['public_prefix'])}"]
    for isp, i, link in isp_neigh:
        L += [f"  neighbor {link['ip']} activate",
              f"  neighbor {link['ip']} route-map RM-{isp}-IN in",
              f"  neighbor {link['ip']} route-map RM-{isp}-OUT out",
              f"  neighbor {link['ip']} maximum-prefix 100 80"]
    L += [f"  neighbor {peer_lo} activate",
          f"  neighbor {peer_lo} next-hop-self",
          " exit-address-family",
          "!",
          f"ip route {net(SITE['public_prefix']).network_address} {mask(SITE['public_prefix'])} {ext['fw_vip']} name PUBLIC-PREFIX-TO-FW-CARP",
          "!"]
    L += cisco_mgmt_services(name, d, d["mgmt"]["port"], " vrf MGMT")
    return L


def core_svi_ip(core, vid):
    return net(VL[vid]["subnet"])[DEV[core]["svi_host"]]


def core_acl(vid):
    """Stateless inbound ACL on a data SVI (PDF Table 18, inter-VLAN part)."""
    src = VL[vid]["subnet"]
    s = acl_net(src)
    A = INV["core_acl"]
    name = f"ACL-VLAN{vid}-IN"
    L = [f"ip access-list extended {name}",
         f" remark VLAN {vid} {VL[vid]['name']} – inbound, default deny towards other internal VLANs",
         f" permit tcp {s} any established",
         " permit udp any host 224.0.0.102 eq 1985",
         " permit 112 any host 224.0.0.18"]
    for r in A["common_out"]:
        for port in r["ports"]:
            L.append(f" permit {r['proto']} {s} {acl_net(r['dst'])} eq {port}")
    for r in A["per_vlan"].get(vid, []):
        if r["proto"] in ("tcp", "udp"):
            for port in r["ports"]:
                L.append(f" permit {r['proto']} {s} {acl_net(r['dst'])} eq {port}")
        else:
            L.append(f" permit {r['proto']} {s} {acl_net(r['dst'])}")
    # stateless replies to requests initiated by monitoring / admin
    L += [f" permit udp {s} eq snmp {acl_net(VL[60]['subnet'])}",
          f" permit udp {s} eq snmp {acl_net(VL[90]['subnet'])}"]
    if vid == 100:
        L += [f" permit udp {s} eq domain 10.0.0.0 0.255.255.255", f" permit udp {s} eq ntp 10.0.0.0 0.255.255.255"]
    if vid == 30:
        L += [f" permit udp {s} eq 2049 {acl_net(VL[20]['subnet'])}", f" permit udp {s} eq sunrpc {acl_net(VL[20]['subnet'])}"]
    for t in ("echo-reply", "unreachable", "time-exceeded", "packet-too-big"):
        L.append(f" permit icmp {s} 10.0.0.0 0.255.255.255 {t}")
    for r in A["deny_log"]:
        L.append(f" deny   ip any {acl_net(r['dst'])} log")
    L += [f" permit tcp {s} {acl_net(VL[50]['subnet'])} eq www",
          f" permit tcp {s} {acl_net(VL[50]['subnet'])} eq 443",
          " deny   ip any 10.0.0.0 0.255.255.255 log",
          f" permit ip {s} any",
          " deny   ip any any log",
          "!"]
    return L


def gen_core(name, d):
    d["_name"] = name
    L, mgmt_src, vrf = cisco_base(name, d)
    other = "CORE-B" if name == "CORE-A" else "CORE-A"
    trunk_data = ",".join(str(v) for v in INV["data_vlans"])
    # a VLAN that both cores also reach through a lab switch (902 on SW-IN) must not cross the ISL: L2 loop
    on_sw = {p["vlan"] for sw in INV["lab_switches"].values() for p in sw["ports"].values()
             if INV["devices"].get(p["to"].split(":")[0], {}).get("role") == "core"}
    trunk_isl = ",".join(str(v) for v in INV["core_vlans"] if v not in on_sw)
    L += ["vtp mode transparent",
          "spanning-tree mode rapid-pvst",
          "spanning-tree extend system-id",
          "spanning-tree loopguard default",
          "errdisable recovery cause bpduguard",
          "errdisable recovery interval 300"]
    # root bridge aligned with HSRP active (PDF 11.6)
    prim = [v for v in INV["core_vlans"] if (VL[v].get("active") == name) or (v in (902, 998) and name == "CORE-A")]
    sec = [v for v in INV["core_vlans"] if v not in prim]
    L += [f"spanning-tree vlan {','.join(map(str, prim))} priority 4096",
          f"spanning-tree vlan {','.join(map(str, sec))} priority 8192", "!"]
    for vid, v in VL.items():
        if vid in INV["core_vlans"] or vid == 999:
            L += [f"vlan {vid}", f" name {v['name']}", "!"]
    L += ["ip routing", "!"]
    L += cisco_mgmt_vrf(d)
    L += ["interface Loopback0", " description Router-ID", f" ip address {d['loopback']} 255.255.255.255", " ip ospf 1 area 0", "!"]
    L += ["interface Port-channel1",
          f" description MDA-{name}:Po1 -> MDA-{other}:Po1 | ISL LACP 802.3ad",
          " switchport trunk encapsulation dot1q",
          " switchport mode trunk",
          f" switchport trunk allowed vlan {trunk_isl}",
          " switchport nonegotiate",
          " no shutdown", "!"]
    for port, p in d["ports"].items():
        if p["mode"] == "mgmt":
            continue
        L += [f"interface {port}", f" description {label(name, port, p['to'], p['role'])}"]
        if p["mode"] == "portchannel":
            L += [" switchport trunk encapsulation dot1q", " switchport mode trunk",
                  f" switchport trunk allowed vlan {trunk_isl}", " switchport nonegotiate",
                  f" channel-group {p['channel']} mode active"]
        elif p["mode"] == "trunk":
            L += [" switchport trunk encapsulation dot1q", " switchport mode trunk",
                  f" switchport trunk allowed vlan {trunk_data}", " switchport nonegotiate"]
        elif p["mode"] == "access":
            L += [" switchport mode access", f" switchport access vlan {p['vlan']}", " switchport nonegotiate",
                  " spanning-tree portfast"]
            if p["to"].split(":")[0] in INV["lab_switches"]:
                # transit segment shared with the other core (SW-IN): no STP across it, else the other core's port is
                # its root port and loop guard blocks it the moment this core dies (FW.3); no loop: VLAN off the ISL
                L += [" spanning-tree bpdufilter enable"]
        L += [" no shutdown", "!"]
    L += unused_ports(d, [f"Gi{s}/{i}" for s in range(4) for i in range(4)], l2=True)
    # SVIs
    for vid in INV["data_vlans"]:
        L += core_acl(vid)
    hk = C["hsrp_key"]
    for vid in INV["core_vlans"]:
        v = VL[vid]
        if vid == 998:
            ip = TR["ospf_core"][name]
            L += [f"interface Vlan{vid}", f" description {v['name']} – OSPF adjacency {name} <-> {other}",
                  f" ip address {ip} {mask(v['subnet'])}", " ip ospf network point-to-point", " ip ospf 1 area 0",
                  " ip ospf authentication message-digest", f" ip ospf message-digest-key 1 md5 {C['ospf_key']}",
                  " ip ospf hello-interval 1", " ip ospf dead-interval 3", " no shutdown", "!"]
            continue
        if vid == 902:
            ip, vip = TR["int"][name], TR["int"]["core_vip"]
            active = "CORE-A"
        else:
            ip, vip, active = core_svi_ip(name, vid), v["vip"], v["active"]
        prio = d["hsrp_active_priority"] if active == name else d["hsrp_standby_priority"]
        L += [f"interface Vlan{vid}", f" description {v['name']} – {v['purpose']}",
              f" ip address {ip} {mask(v['subnet'])}", " no ip redirects", " no ip proxy-arp"]
        if vid in INV["data_vlans"]:
            L.append(f" ip access-group ACL-VLAN{vid}-IN in")
        # 1 s / 3 s: with 250/750 ms on eight groups the emulated IOSvL2 cores miss hellos under load and HSRP
        # flaps without end (PLAN_03 S1, 20 Oct 2026); failover takes ~3 s instead of < 1 s (lab deviation)
        L += [" ip ospf 1 area 0",
              " standby version 2", f" standby {vid} ip {vip}", f" standby {vid} priority {prio}",
              f" standby {vid} preempt delay minimum 30", f" standby {vid} timers 1 3",
              f" standby {vid} authentication md5 key-string {hk}", f" standby {vid} name HSRP-VLAN{vid}"]
        if vid == 902:
            L += [" ip ospf authentication message-digest", f" ip ospf message-digest-key 1 md5 {C['ospf_key']}"]
        L += [" no shutdown", "!"]
    L += ["interface Vlan1", " no ip address", " shutdown", "!",
          "router ospf 1", f" router-id {d['loopback']}", " auto-cost reference-bandwidth 100000",
          " passive-interface default", " no passive-interface Vlan998", " no passive-interface Vlan902",
          " log-adjacency-changes detail", "!",
          f"ip route 0.0.0.0 0.0.0.0 {TR['int']['fw_vip']} name DEFAULT-VIA-FW-CARP", "!"]
    L += cisco_mgmt_services(name, d, d["mgmt"]["port"], " vrf MGMT")
    return L


def gen_leaf(name, d):
    d["_name"] = name
    L, _, _ = cisco_base(name, d)
    trunk_data = ",".join(str(v) for v in INV["data_vlans"])
    L += ["vtp mode transparent", "spanning-tree mode rapid-pvst", "spanning-tree extend system-id",
          "spanning-tree loopguard default", "errdisable recovery cause bpduguard", "errdisable recovery interval 300", "!"]
    for vid in [10] + INV["data_vlans"] + [999]:
        L += [f"vlan {vid}", f" name {VL[vid]['name']}", "!"]
    L += ["no ip routing", "!"]
    for port, p in d["ports"].items():
        L += [f"interface {port}", f" description {label(name, port, p['to'], p['role'])}"]
        if p["mode"] == "trunk":
            L += [" switchport trunk encapsulation dot1q", " switchport mode trunk",
                  f" switchport trunk allowed vlan {trunk_data}", " switchport nonegotiate"]
        elif p["mode"] == "access":
            L += [" switchport mode access", f" switchport access vlan {p['vlan']}", " switchport nonegotiate",
                  " spanning-tree portfast", " spanning-tree bpduguard enable"]
            # storm-control: not implemented by the IOSvL2 image (rejected), kept for physical switches
            if d["platform"] != "iosvl2":
                L += [" storm-control broadcast level 10.00", " storm-control action trap"]
        elif p["mode"] == "mgmt":
            # bpdufilter: every switch's OOB port meets the others on SW-MGMT, so they exchanged BPDUs over VLAN 10 and
            # the OOB port became a root port; when a core hung, loop guard blocked it and the leaf left management
            # (LEAF-B1/B2, 10 Nov 2026). VLAN 10 is on this single port per leaf (never trunked): no loop possible.
            L += [" switchport mode access", " switchport access vlan 10", " switchport nonegotiate", " spanning-tree portfast",
                  " spanning-tree bpdufilter enable"]
        L += [" no shutdown", "!"]
