"""Generate device configurations and report tables from inventory/dc_casa.yaml.

Outputs
  configs/<DEVICE>.cfg                Cisco IOSv / IOSvL2 (EDGE, CORE, LEAF)
  configs/ISP-A/frr.conf, daemons     FRR for the operator containers
  configs/servers/<SRV>.netplan.yaml  Ubuntu netplan (bond active-backup)
  configs/docker/<NODE>.interfaces    /etc/network/interfaces for GNS3 docker nodes
  configs/docker/ADMIN-WS.ssh_config  SSH aliases of the administration webterm (one per equipment)
  configs/docker/ADMIN-WS.portal.html start page of its browser (every web interface)
  report/content/generated/*.md       tables included by the report

Usage: python automation/gen_configs.py   (idempotent; re-run after editing the inventory)
"""
import ipaddress
from pathlib import Path

import yaml

NET = Path(__file__).resolve().parents[1]
INV = yaml.safe_load((NET / "inventory" / "dc_casa.yaml").read_text(encoding="utf-8"))
CFG = NET / "configs"
GEN = NET / "report" / "content" / "generated"
C = INV["credentials"]
S = INV["services"]
SITE = INV["site"]
VL = INV["vlans"]
DEV = INV["devices"]
TR = INV["transit"]


def net(cidr):
    return ipaddress.ip_network(cidr)


def mask(cidr):
    return str(net(cidr).netmask)


def wild(cidr):
    return str(net(cidr).hostmask)


def ipmask(iface):
    i = ipaddress.ip_interface(iface)
    return f"{i.ip} {i.netmask}"


def acl_net(x):
    """'any' | host | network in IOS extended ACL syntax"""
    if x == "any":
        return "any"
    n = net(x if "/" in x else f"{x}/32")
    return f"host {n.network_address}" if n.prefixlen == 32 else f"{n.network_address} {n.hostmask}"


def node_space(name):
    if name in DEV:
        return DEV[name]["tia"]
    if name in INV["lab_switches"]:
        return INV["lab_switches"][name]["tia"]
    if name in INV["servers"]:
        return INV["servers"][name]["tia"]
    if name in INV["isps"]:
        return "ER"
    return "EXT"


def label(dev, port, to, role):
    """ANSI/TIA-606-C style: SPACE-DEVICE:port -> SPACE-DEVICE:port | role"""
    peer, pport = to.split(":")
    return f"{node_space(dev)}-{dev}:{port} -> {node_space(peer)}-{peer}:{pport} | {role}"[:200]


def ascii_only(text):
    """IOS consoles reject non-ASCII bytes: transliterate accents and typographic dashes (é->e, –->-, œ->oe)."""
    import unicodedata
    text = text.replace("–", "-").replace("—", "-").replace("œ", "oe").replace("Œ", "OE").replace("’", "'")
    return unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()


def write(path, text):
    if path.suffix == ".cfg":
        text = ascii_only(text)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")


