# =========================================================================================== main
def main():
    count = 0
    for name, d in DEV.items():
        d = dict(d)
        if d["role"] == "edge":
            write(CFG / f"{name}.cfg", "\n".join(gen_edge(name, d))); count += 1
        elif d["role"] == "core":
            write(CFG / f"{name}.cfg", "\n".join(gen_core(name, d))); count += 1
        elif d["role"] == "leaf":
            write(CFG / f"{name}.cfg", "\n".join(gen_leaf(name, d))); count += 1
    for name, i in INV["isps"].items():
        write(CFG / name / "frr.conf", "\n".join(gen_isp(name, i)))
        write(CFG / name / "daemons", DAEMONS)
        write(CFG / name / "interfaces", gen_isp_if(name, i))
        count += 1
    for name, s in INV["servers"].items():
        if s.get("platform") == "truenas":      # network set on the appliance itself (NAS.3), no netplan
            pass
        elif s["kind"] == "vm":
            write(CFG / "servers" / f"{name}.netplan.yaml", gen_netplan(name, s))
        elif s["image"] not in ("gns3/webterm:latest",) or True:
            write(CFG / "docker" / f"{name}.interfaces", gen_docker_if(name, s))
        count += 1
    write(CFG / "docker" / "ADMIN-WS.ssh_config", gen_admin_ssh())
    write(CFG / "docker" / "ADMIN-WS.portal.html", gen_admin_portal())
    T = gen_tables()
    print(f"generated {count} device/server configs, {len(T)} report tables")


if __name__ == "__main__":
    main()
