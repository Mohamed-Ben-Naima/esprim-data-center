def cisco_base(name, d):
    space = d["tia"]
    mgmt_src = d["mgmt"]["port"] if d["role"] != "leaf" else "Vlan10"
    vrf = " vrf MGMT" if d["role"] in ("edge", "core") else ""
    old_ios = d["platform"] == "iosvl2"
    secret = "secret" if old_ios else "algorithm-type scrypt secret"
    L = [
        "! " + "=" * 92,
        f"! {name} – {d['role'].upper()} – {d['platform']} – TIA-942 space {space}",
        "! Generated by automation/gen_configs.py from inventory/dc_casa.yaml – do not edit by hand",
        "! " + "=" * 92,
        "version 15.2" if old_ios else "version 15.9",
        "service timestamps debug datetime msec localtime show-timezone",
        "service timestamps log datetime msec localtime show-timezone",
        "service password-encryption",
        "service tcp-keepalives-in",
        "service tcp-keepalives-out",
        "no service pad",
        "!",
        f"hostname {name}",
        "!",
        "clock timezone MAR 1 0",
        "no ip domain-lookup",
        f"ip domain-name {SITE['domain']}",
        "no ip http server",
        "no ip http secure-server",
        "no ip source-route",
        "no ip bootp server",
        "!",
        f"enable {secret} {C['enable_secret']}",
        f"username {C['admin_user']} privilege 15 {secret} {C['admin_password']}",
        "aaa new-model",
        "aaa authentication login default local",
        "aaa authorization exec default local",
        "login block-for 120 attempts 5 within 60",
        "login on-failure log",
        "login on-success log",
        "!",
        "crypto key generate rsa modulus 2048",
        "ip ssh version 2",
        "ip ssh time-out 60",
        "ip ssh authentication-retries 3",
        "!",
        "lldp run",
        "!",
    ]
    return L, mgmt_src, vrf


