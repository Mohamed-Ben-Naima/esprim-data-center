def gen_isp(name, i):
    first_ip = next(iter(i["links"].values()))["ip"]
    L = [f"! {name} – AS{i['asn']} – FRR – generated from inventory/dc_casa.yaml",
         "frr version 8", "frr defaults traditional", f"hostname {name}", "log syslog informational",
         "service integrated-vtysh-config", "!"]
    for port, l in i["links"].items():
        plen = net(l["net"]).prefixlen
        L += [f"interface {port}", f" description ER-{name}:{port} -> ER-{l['peer']} | eBGP AS{SITE['asn']}",
              f" ip address {l['ip']}/{plen}", "!"]
    L += [f"ip prefix-list PL-FROM-DC seq 10 permit {SITE['public_prefix']}", "!",
          "route-map RM-DENY-ALL deny 10", "!",
          f"router bgp {i['asn']}", f" bgp router-id {first_ip}", " bgp log-neighbor-changes",
          " no bgp ebgp-requires-policy", " no bgp network import-check"]
    for port, l in i["links"].items():
        L += [f" neighbor {l['peer_ip']} remote-as {SITE['asn']}", f" neighbor {l['peer_ip']} description {l['peer']}",
              f" neighbor {l['peer_ip']} password {C['bgp_password']}", f" neighbor {l['peer_ip']} timers 3 9"]
    L += [" !", " address-family ipv4 unicast"]
    for port, l in i["links"].items():
        L += [f"  neighbor {l['peer_ip']} default-originate", f"  neighbor {l['peer_ip']} prefix-list PL-FROM-DC in",
              f"  neighbor {l['peer_ip']} route-map RM-DENY-ALL out", f"  neighbor {l['peer_ip']} maximum-prefix 10"]
    L += [" exit-address-family", "!", "line vty", "!"]
    return L


