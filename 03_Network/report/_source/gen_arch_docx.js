const fs = require("fs");
function fig(imgPath, caption, w = 600, hgt = 450) {
  const buf = fs.readFileSync(imgPath);
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 }, children: [new ImageRun({ data: buf, transformation: { width: w, height: hgt }, type: "png" })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: [t(caption, { italics: true, size: 18, color: MUTED })] }),
  ];
}
function codeBlock(filePath) {
  const src = fs.readFileSync(filePath, "utf8").trim().split("\n");
  return src.map((ln) => new Paragraph({ spacing: { after: 0, line: 240 }, shading: { fill: "F4F6F8", type: ShadingType.CLEAR, color: "auto" }, children: [new TextRun({ text: ln || " ", font: "Consolas", size: 15, color: "0B5560" })] }));
}

