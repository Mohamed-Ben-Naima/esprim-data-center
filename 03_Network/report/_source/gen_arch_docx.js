function h(level, text) {
  const hl = [HeadingLevel.HEADING_1, HeadingLevel.HEADING_2, HeadingLevel.HEADING_3][level - 1];
  return new Paragraph({ heading: hl, pageBreakBefore: level === 1, keepNext: true, children: [t(text, { bold: level === 1, size: level === 1 ? 30 : 26, color: level === 1 ? ACCENT : DARK })] });
}
function table(head, body) {
  const n = head.length;
  const len = head.map((hh, i) => Math.min(46, Math.max(8, ...[hh, ...body.map((r) => r[i] || "")].map((s) => s.length))));
  const tot = len.reduce((a, b) => a + b, 0);
  const widths = len.map((l) => Math.floor(W * l / tot));
  widths[n - 1] += W - widths.reduce((a, b) => a + b, 0);
  const cell = (txt, i, isHead, zebra) => new TableCell({
    borders, width: { size: widths[i], type: WidthType.DXA }, verticalAlign: VerticalAlign.CENTER,
    shading: isHead ? { fill: DARK, type: ShadingType.CLEAR, color: "auto" } : zebra ? { fill: ZEBRA, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 50, bottom: 50, left: 90, right: 90 },
    children: [new Paragraph({ spacing: { after: 0, line: 252 }, children: [t(txt, isHead ? { bold: true, color: "FFFFFF", size: 17 } : { size: 17 })] })],
  });
  return [new Table({ width: { size: W, type: WidthType.DXA }, columnWidths: widths,
    rows: [new TableRow({ tableHeader: true, children: head.map((x, i) => cell(x, i, true)) }),
      ...body.map((r, ri) => new TableRow({ children: head.map((_, i) => cell(r[i] || "", i, false, ri % 2 === 1)) }))] }),
    new Paragraph({ spacing: { after: 160 }, children: [] })];
}

